import { readFileSync, writeFileSync } from 'node:fs';
import { ADMIN_RULES } from '../src/admin/config.js';
const file = new URL('../supabase/migrations/20261008_test_admin.sql', import.meta.url);
const old = readFileSync(file, 'utf8');
const block = `-- ADMIN_RULES BEGIN\n-- generated by tools/build-admin-config.mjs\ninsert into game_admin.settings(key,value) values ('rules', $rules$${JSON.stringify(ADMIN_RULES)}$rules$::jsonb) on conflict(key) do update set value=excluded.value;\n-- ADMIN_RULES END`;
const next = old.replace(/-- ADMIN_RULES BEGIN[\s\S]*?-- ADMIN_RULES END/, block);
if (process.argv.includes('--check')) { if (old !== next) throw new Error('Admin SQL catalog is outdated: run node tools/build-admin-config.mjs'); }
else writeFileSync(file, next);

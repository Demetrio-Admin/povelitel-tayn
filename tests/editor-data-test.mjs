import assert from 'node:assert/strict';
import { ASSET_FILES } from '../src/config/assets.manifest.js';
import { ASSET_CATALOG, assetGroup, defaultAssetSolid } from '../src/world/assetCatalog.js';
import { BUILDINGS, CITY_PORTALS } from '../src/config/city.plan.js';
import { buildingDoor, linkBuildingPortals } from '../src/world/buildingGeometry.js';
import { WORLD_DECOR, DECOR_SOLID } from '../src/world/decorData.js';
import { propSolid } from '../src/world/solids.js';
import { PROPS, applyEdits, diffEdits, applyPos, diffPos, baseTerrain, applyTerrainEdits, diffTerrain, parseEditsFile, exportEditsFile } from '../src/world/mapData.js';

const copy=v=>structuredClone(v);
assert.deepEqual(new Set(ASSET_CATALOG.map(a=>a.key)),new Set(Object.keys(ASSET_FILES).filter(k=>ASSET_FILES[k])));
assert.equal(new Set(PROPS.map(p=>p.id)).size,PROPS.length);
for(const id of ['city_plan_archive_sign','city_plan_gate_post_n','city_plan_rescued_cellar','forest_border_0'])assert.ok(PROPS.some(p=>p.id===id));
// v0.34.3: лес-заполнитель и плоский декор проходимы; стоячие предметы и люди из таблицы DECOR_SOLID — нет
assert.ok(WORLD_DECOR.every(p=>propSolid(p)===null||(!p.fill&&DECOR_SOLID[p.k])),'only listed standing decor has a collision footprint');
assert.ok(WORLD_DECOR.filter(p=>p.fill).every(p=>propSolid(p)===null),'forest filler stays walkable');
for(const id of ['city_resident_man','city_resident_woman','city_patient_miron','bank_lamp_w','city_market_crate'])assert.ok(propSolid(WORLD_DECOR.find(p=>p.id===id)),`${id} is solid`);
assert.equal(propSolid({k:'lantern_01',x:100,y:200,solid:null}),null);
assert.ok(propSolid({k:'city_crate',x:100,y:200,solid:'auto'}));
assert.deepEqual(propSolid({k:'city_crate',x:100,y:200,s:2,solid:{w:50,h:25}}),{x:50,y:150,w:100,h:50});
assert.equal(defaultAssetSolid('flower_white_01'),null);
console.log('  ✓ Каталог полон, идентификаторы уникальны, старый декор не меняет коллизии');

const before=[{id:'lamp',k:'lantern_01',x:100,y:200,f:1},{id:'flower',k:'flower_white_01',x:120,y:220}];
const after=[{id:'lamp',k:'city_crate',x:150,y:250,s:1.4,a:30,l:'front',solid:{w:45,h:20},alpha:0.5,fill:0},{id:'added',k:'flower_purple_01',x:160,y:280}];
const edits=diffEdits(before,after);
const restored=applyEdits(before,edits);
assert.equal(edits.props.flower,null);
assert.equal(!!restored[0].f,false);
assert.deepEqual(restored[0].solid,{w:45,h:20});
assert.deepEqual(diffEdits(before,restored),edits);
const walkable=diffEdits(before,[{...before[0],solid:null},before[1]]);
assert.deepEqual(walkable.props.lamp,{solid:null});
assert.equal(propSolid(applyEdits(before,walkable)[0]),null);
assert.deepEqual(before,[{id:'lamp',k:'lantern_01',x:100,y:200,f:1},{id:'flower',k:'flower_white_01',x:120,y:220}]);
const objs=[{id:'npc',x:50,y:60,target:{x:70,y:80},approach:{x:50,y:150},panOnOpen:{x:90,y:100}},{id:'enemy',x:120,y:130}];
const pos={npc:{x:150,texture:'npc_banker',editorStyle:{s:0.8,f:1,l:'front'}},enemy:null};
const moved=applyPos(objs,pos);
assert.equal(moved.length,1);assert.deepEqual(moved[0].target,{x:170,y:80});
assert.deepEqual(moved[0].panOnOpen,{x:190,y:100});
assert.deepEqual(moved[0].approach,{x:150,y:150},'moving an NPC preserves the visitor spot');
assert.deepEqual(diffPos(objs,pos),pos);
assert.deepEqual(applyPos(objs,{npc:{editorStyle:{a:15}}})[0].target,objs[0].target);
console.log('  ✓ Полные параметры, замена, удаление и связанные точки сюжетных объектов сохраняются');

const terrain=baseTerrain(),changed=copy(terrain);
changed.grounds[0].w+=123;changed.grounds[0].tex='city_stone_floor';
changed.grounds.splice(1,1);changed.grounds.push({id:'gr100',x:100,y:200,w:300,h:400,tex:'city_wood_floor',tileScale:0.65});
const terrainEdits=diffTerrain({...changed,colliders:changed.cols});
assert.deepEqual(applyTerrainEdits(terrainEdits).grounds,changed.grounds);
assert.deepEqual(applyTerrainEdits({v:1,props:{},add:[],pos:{}}).grounds,terrain.grounds);
assert.deepEqual(parseEditsFile(exportEditsFile({...edits,...terrainEdits,pos})),{...edits,...terrainEdits,pos});
assert.deepEqual(parseEditsFile(JSON.stringify(edits)),edits);
assert.throws(()=>parseEditsFile('export const EDITS = {"v":1}; globalThis.__unexpected=true;'));
assert.throws(()=>parseEditsFile('{"v":2}'));
assert.throws(()=>parseEditsFile('{"v":1,"add":{}}'));
assert.equal(globalThis.__unexpected,undefined);
console.log('  ✓ Полы и старые черновики совместимы; импорт читает данные без выполнения JavaScript');

const bank=BUILDINGS.find(b=>b.id==='bank'),baseBank=terrain.cols.find(c=>c.building==='bank');
assert.deepEqual(buildingDoor(baseBank),bank.door);
const editedBank={...copy(baseBank),x:baseBank.x+120,y:baseBank.y-80};
const linked=linkBuildingPortals(CITY_PORTALS,[editedBank]);
const entrance=linked.find(o=>o.id==='door_bank'),exit=linked.find(o=>o.id==='room_exit_bank');
assert.deepEqual([entrance.x,entrance.y],[bank.door.x+120,bank.door.y+28-80]);
assert.deepEqual(entrance.target,CITY_PORTALS.find(o=>o.id==='door_bank').target,'interior stays fixed');
assert.deepEqual(exit.target,{x:bank.door.x+120,y:bank.door.y+100-80});
assert.deepEqual(applyPos([entrance],{door_bank:{x:entrance.x+10}})[0].target,entrance.target,'moving portal does not move its destination');
const bankPatches=diffTerrain({...terrain,colliders:terrain.cols.map(c=>c.id===baseBank.id?editedBank:c)});
const roundtrip=applyTerrainEdits(parseEditsFile(exportEditsFile({v:1,layout:2,...bankPatches})));
assert.deepEqual(linkBuildingPortals(CITY_PORTALS,roundtrip.colliders),linkBuildingPortals(CITY_PORTALS,terrain.cols.map(c=>c.id===baseBank.id?editedBank:c)));
assert.deepEqual(baseBank.x,bank.x,'original layout untouched');
assert.ok(terrain.grounds.some(g=>g.id==='city_lawn'&&g.l==='ground'));
const facade=ASSET_CATALOG.find(a=>a.key==='city_final_bank_exterior');
assert.ok(facade.frame&&facade.src.includes('facades-south'));
assert.match(facade.name,/Банк/);
assert.equal(assetGroup('city_walk_tree_sage'),'nature');
assert.equal(assetGroup('city_walk_lawn'),'ground');
console.log('  ✓ Новые фасады, трава, перенос входа и возврата сохраняются; комната остаётся на месте');

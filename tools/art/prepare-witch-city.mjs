import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const source=path.join(root,'docs/design/city-witch-v1');
const layout=JSON.parse(await fs.readFile(path.join(source,'city-layout.json'),'utf8'));
// Doorstep centres in the approved atlas. Transparent padding is omitted from the frames.
const doors={north_bay:[249,454],north_workshop:[756,455],cellar:[1292,462],rescue:[246,928],archive:[756,929],society:[1248,928],
  bank:[285,492],duel:[767,492],coven:[1304,492],warehouse_a:[268,949],warehouse_b:[815,951],lab:[1264,951]};
const sprites={};
for(const [id,data] of Object.entries(layout.facadeFrames)){
  const f=data.frame,b=data.visibleBoundsAlpha32,door=doors[id];
  const x=f.x+b.x,y=f.y+b.y;
  sprites['city_final_'+id+'_exterior']={atlas:data.image.includes('north')?'city_witch_north':'city_witch_south',
    frame:{x,y,w:b.w,h:b.h},anchor:{x:(door[0]-x)/b.w,y:(door[1]-y)/b.h}};
}
const atlases={city_witch_north:'assets/city-witch/facades-north-v1.webp',city_witch_south:'assets/city-witch/facades-south-v1.webp'};
await fs.writeFile(path.join(root,'src/config/city.witch.art.js'),
  '// Approved multicolored witch town; generated by tools/art/prepare-witch-city.mjs.\n'+
  'export const CITY_WITCH_ATLASES = '+JSON.stringify(atlases,null,2)+';\n'+
  'export const CITY_WITCH_SPRITES = '+JSON.stringify(sprites,null,2)+';\n');
console.log('Prepared 12 facade frames with door anchors.');

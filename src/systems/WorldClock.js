// v0.9.1 — покадровые изменения состояния мира (время игры, восстановление HP и маны). Без Phaser.
// Вынесено из ExplorationScene.update, чтобы одно и то же правило работало в игре и в тестах.
//
// Пока выполняется атомарное действие сервера (лечение у Мирры, стартовый набор — services.actions.busy), мир стоит:
// время игры не идёт, HP и мана не восстанавливаются, героиня не двигается. Тогда снимок, который PlayerSession
// отправляет перед действием, не устаревает за время запроса, и сервер применяет действие к тому же состоянию,
// которое видит игрок. Запрос длится доли секунды — заметить остановку почти невозможно.
import * as vitals from '../state/vitals.js';

/** Идёт ли сейчас действие сервера, на время которого мир замирает. */
export const serverActionBusy = (services) => !!services?.actions?.busy;

/**
 * Один кадр мира. deltaMs — длительность кадра.
 *  frozen — действие сервера: ничего не меняется;
 *  active — героиня в мире и может действовать (нет окон, боя, перехода): идёт восстановление;
 *  inHouse — дом Мирры (мана быстрее).
 * Время игры идёт и при открытых окнах/диалогах (как раньше), но не во время действия сервера.
 * Возвращает true, если изменились HP или мана.
 */
export function advanceWorld(state, deltaMs, { frozen = false, active = true, inHouse = false } = {}) {
  if (frozen || !(deltaMs > 0)) return false;
  state.data.stats.playTimeMs += deltaMs;
  if (!active) return false;
  return vitals.regen(state, Math.min(deltaMs, 50) / 1000, { inHouse });
}

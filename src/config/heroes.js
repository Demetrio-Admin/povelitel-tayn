// Стартовые герои (v0.9.2): ведьма и колдун — две версии одного персонажа.
// Выбор влияет только на внешность, название и обращения; дары, характеристики, XP, крафт, цены, квесты и награды — общие
// (они не описываются здесь и не копируются в героя).
// Онлайн выбор хранится в profiles.hero_id (сервер возвращает его как meta.hero), без сервера — в сохранении (heroId).
// id — латиница, цифры и _ (так проверяет сервер). Старый id 'witch' не менять: на нём профили и сохранения до v0.9.2.
//
// Вся карта внешности — здесь: textures.{down, up, side} — ключи текстур (лево = зеркало side), портрет медальона
// кадрируется из textures.down. Холсты ракурсов одного размера у всех героев (166×240), ноги у нижнего края:
// размер на экране, тень, hitbox и зоны взаимодействия общие (config/game.config.js PLAYER).

export const DEFAULT_HERO_ID = 'witch';

/** Общий короткий текст о дарах (одинаков для обоих героев). */
export const HERO_SHARED_TEXT = 'Владеет Телекинезом и Лунным огнём. Двигает камни, сжигает преграды и прерывает удары врагов.';
export const HERO_SAME_NOTE = 'Дары и характеристики одинаковые';

export const HEROES = [
  {
    id: 'witch',
    gender: 'female',
    name: 'Ведьма',
    title: 'Ученица лесной ведьмы',
    textures: { down: 'hero_down', up: 'hero_up', side: 'hero_side' },
  },
  {
    id: 'warlock',
    gender: 'male',
    name: 'Колдун',
    title: 'Ученик лесной ведьмы',
    textures: { down: 'warlock_down', up: 'warlock_up', side: 'warlock_side' },
  },
];

const BY_ID = new Map(HEROES.map(h => [h.id, h]));

/** Известен ли герой с таким id. */
export const isKnownHero = (id) => BY_ID.has(id);

/**
 * Определение героя для показа. Неизвестный или пустой id безопасно показывается как ведьма (стандартный герой);
 * сам id при этом нигде не переписывается — это делает только явный выбор игрока при создании или новой игре.
 */
export const heroById = (id) => BY_ID.get(id) || BY_ID.get(DEFAULT_HERO_ID);

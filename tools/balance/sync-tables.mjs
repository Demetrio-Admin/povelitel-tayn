function parseCsv(raw) {
  const source = raw.replace(/^\uFEFF/, '').replace(/(?:\r\n|\n|\r)+$/, '') + '\n';
  const field = /(?:"((?:[^"]|"")*)"|([^",\r\n]*))(,|\r\n|\n|\r)/y;
  const rows = [];
  let row = [];
  while (field.lastIndex < source.length) {
    const match = field.exec(source);
    if (!match) throw new Error('Invalid CSV quoting at row ' + (rows.length + 1));
    row.push(match[1]?.replaceAll('""', '"') ?? match[2]);
    if (match[3] !== ',') {
      rows.push(row);
      row = [];
    }
  }
  return rows;
}

function readTable(name, schema) {
  const file = new URL('balance-tables/' + name + '.csv', root);
  const [header, ...records] = parseCsv(readFileSync(file, 'utf8'));
  const ids = [schema.id].flat();
  const required = [...ids, ...(schema.number ?? []), ...(schema.json ?? [])];
  if (new Set(header).size !== header.length || required.some(key => !header.includes(key))) {
    throw new Error(name + ': missing or duplicate columns');
  }
  const seen = new Set();
  const rows = records.map((cells, index) => {
    try {
      if (cells.length !== header.length) throw new Error('column count does not match the header');
      const row = Object.fromEntries(header.map((key, i) => [key, parseCell(key, cells[i], schema)]));
      const identity = JSON.stringify(ids.map(key => row[key]));
      if (ids.some(key => row[key] === null) || seen.has(identity)) throw new Error('empty or duplicate identity');
      seen.add(identity);
      return row;
    } catch (error) {
      throw new Error(name + '.csv:' + (index + 2) + ': ' + error.message);
    }
  });
  if (schema.count && rows.length !== schema.count) throw new Error(name + ': expected ' + schema.count + ' rows');
  if (name === 'encounter_packs') {
    for (const row of rows) {
      for (const field of ['hp_shares', 'dps_shares', 'first_attack_sec']) {
        const values = row[field];
        if (field === 'first_attack_sec' && values === null) continue;
        if (!Array.isArray(values) || values.length !== row.count || values.some(n => !Number.isFinite(n) || n <= 0)) {
          throw new Error(name + ': invalid ' + field + ' for ' + row.pack_id);
        }
      }
    }
  }
  return rows;
}

function parseCell(key, value, schema) {
  if (value === '') return null;
  if (schema.number?.includes(key)) {
    const number = Number(value);
    if (!Number.isFinite(number) || value.trim() === '') throw new Error(key + ' must be numeric');
    return number;
  }
  if (schema.json?.includes(key)) return JSON.parse(value);
  if (key === 'enabled') {
    if (!['true', 'false'].includes(value)) throw new Error('enabled must be true or false');
    return value === 'true';
  }
  return value;
}

const result = Object.fromEntries(Object.entries(tables).map(([name, schema]) => [name, readTable(name, schema)]));
const target = new URL('src/config/horizon/tables.generated.js', root);
const moduleText = '// Generated by npm run balance:sync. Edit balance-tables/*.csv.\n'
  + 'export const HORIZON_TABLES = ' + JSON.stringify(result, null, 2) + ';\n';

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== moduleText) {
    throw new Error('Generated balance differs from CSV. Run npm run balance:sync.');
  }
} else {
  mkdirSync(new URL('./', target), { recursive: true });
  writeFileSync(target, moduleText);
}
console.log('Validated ' + Object.keys(result).length + ' balance tables.');
